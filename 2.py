import random
import streamlit as st

# 페이지 제목 설정
st.title("오늘의 운세 보기 🔮")
st.write("자신의 띠를 선택하고 오늘의 운세를 확인해 보세요!")

# 12지신(띠) 리스트
animal_signs = [
    "쥐띠",
    "소띠",
    "호랑이띠",
    "토끼띠",
    "용띠",
    "뱀띠",
    "말띠",
    "양띠",
    "원숭이띠",
    "닭띠",
    "개띠",
    "돼지띠",
]

# 운세 메시지 풀이 예시
fortune_messages = [
    "오늘은 작은 노력으로도 큰 성취를 거둘 수 있는 행운의 날입니다. 🌟",
    "뜻밖의 귀인을 만나 고민하던 문제가 순조롭게 해결될 것입니다. 🤝",
    "조급한 마음을 버리고 여유를 가지면 평온하고 기분 좋은 하루가 됩니다. ☕",
    "새로운 도전이나 계획을 시작하기에 아주 좋은 에너지가 가득한 날입니다. 🚀",
    "주변 사람들과의 소통에서 따뜻한 배려가 큰 행운으로 돌아옵니다. 💖",
    "잠시 휴식을 취하며 재충전의 시간을 가지면 좋은 아이디어가 떠오릅니다. 🌿",
]

# selectbox를 통한 띠 선택
selected_sign = st.selectbox("당신의 띠를 선택하세요:", animal_signs)

# 운세 확인 버튼
if st.button("오늘의 운세 확인하기"):
    # 선택된 띠에 따라 일관된 느낌을 주도록 띠 이름을 시드값으로 활용하거나 랜덤 선택
    # 여기서는 재미를 위해 매번 랜덤한 운세가 나오도록 구성했습니다.
    todays_fortune = random.choice(fortune_messages)

    st.success(f"**{selected_sign}**의 오늘의 운세입니다.")
    st.info(todays_fortune)